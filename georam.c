volatile uint8_t* VIC_2MHZ=(void*)0xd030;

uint8_t read_ram8( uint32_t addr ) {
#ifdef C128
  *VIC_2MHZ = 252;
#endif
    *(volatile uint8_t*)0xdfff = addr >> 14;
    *(volatile uint8_t*)0xdffe = addr >> 8 & 0x3f;
    uint8_t temp = ((volatile uint8_t*)0xde00)[addr & 0xff];
#ifdef C128
  *VIC_2MHZ = 253;
#endif
    return temp;
}
void write_ram8( uint32_t addr, volatile uint8_t data ) {
#ifdef C128
  *VIC_2MHZ = 252;
#endif
    *(volatile uint8_t*)0xdfff = addr >> 14;
    *(volatile uint8_t*)0xdffe = addr >> 8 & 0x3f;
    ((volatile uint8_t*)0xde00)[addr & 0xff] = data;
#ifdef C128
  *VIC_2MHZ = 253;
#endif
}

// reads from 0xffff will have incorrect high byte
uint16_t read_ram16( uint32_t addr ) {
#ifdef C128
  *VIC_2MHZ = 252;
#endif
  *(volatile uint8_t*)0xdfff = addr >> 14;
  *(volatile uint8_t*)0xdffe = addr >> 8 & 0x3f;
  uint16_t temp;
  if( (addr & 255) < 255 ) {
    temp = *(uint16_t*)&((volatile uint8_t*)0xde00)[addr & 0xff];
  } else {
    temp = ((volatile uint8_t*)0xde00)[255];
    *(volatile uint8_t*)0xdfff = (addr + 256) >> 14;
    *(volatile uint8_t*)0xdffe = (addr + 256) >> 8 & 0x3f;
    temp |= (uint16_t)((volatile uint8_t*)0xde00)[0] << 8;
  }
#ifdef C128
  *VIC_2MHZ = 253;
#endif
  return temp;
}

// write to 0xffff will have incorrect high byte,
// but that appears to be consistent with what the 80186 does
void write_ram16( uint32_t addr, uint16_t val ) {
#ifdef C128
  *VIC_2MHZ = 252;
#endif
  *(volatile uint8_t*)0xdfff = addr >> 14;
  *(volatile uint8_t*)0xdffe = addr >> 8 & 0x3f;
  if( (addr & 255) < 255 ) {
    *(uint16_t*)&((volatile uint8_t*)0xde00)[addr & 0xff] = val;
  } else {
    ((volatile uint8_t*)0xde00)[255] = val;
    *(volatile uint8_t*)0xdfff = (addr + 256) >> 14;
    *(volatile uint8_t*)0xdffe = (addr + 256) >> 8 & 0x3f;
    ((volatile uint8_t*)0xde00)[0] = val >> 8;
  }
#ifdef C128
  *VIC_2MHZ = 253;
#endif
}

